describe("LaneManager network pre-flight", () => {
  const filled = (count: number) => ["bridge", "host", "none", ...Array.from({ length: count }, (_, i) => `other_${i}`)];

  test("a lane is not started when Docker has no subnets left for its 7 networks, and says how to make room", async () => {
    await manager.create({ name: "alpha" });
    flisk.networks = { capacity: 31, names: filled(25) };
    await expect(manager.start("alpha")).rejects.toMatchObject({ code: "NO_NETWORK_ROOM" });
    expect(flisk.calls).toEqual([]);
  });

  test("a lane whose networks already exist needs no new room", async () => {
    await manager.create({ name: "alpha" });
    const own = ["backend", "database", "infisical-network", "proxy", "traefik-private", "traefik-public", "verdaccio-network"];
    flisk.networks = { capacity: 31, names: [...filled(23), ...own.map((n) => `alpha_lane_${n}`)] };
    expect((await manager.start("alpha")).ok).toBe(true);
  });

  test("parallel starts cannot both take the last room", async () => {
    flisk.upDelayMs = 20;
    await manager.create({ name: "alpha" });
    await manager.create({ name: "beta" });
    flisk.networks = { capacity: 31, names: filled(20) }; // room for exactly one lane
    const results = await Promise.allSettled([manager.start("alpha"), manager.start("beta")]);
    expect(results.map((r) => r.status).sort()).toEqual(["fulfilled", "rejected"]);
  });
});

describe("LaneManager chaos and rebuild helpers (for Arena)", () => {
  test("each helper reaches only the named lane: its Tilt, its Compose project", async () => {
    const lane = await manager.create({ name: "alpha" });
    await manager.waitForBuilds("alpha", ["worker"], 1234);
    await manager.containerAction("alpha", "db", "stop");
    expect(await manager.restartCount("alpha", "worker")).toBe(2);
    expect(flisk.calls).toEqual([
      `waitForBuilds ${lane.dir} 10401 worker 1234`,
      "stop alpha-lane db",
      "restartCount alpha-lane worker",
    ]);
  });
});
