import { cpSync, mkdirSync, readdirSync } from "node:fs";
import { basename, join, relative, sep } from "node:path";

/** Folders a lane must not inherit, wherever they appear: dependencies and Flisk's generated output. */
const SKIP_ANYWHERE = new Set(["node_modules", ".autogenerated", ".git"]);
/** Paths skipped relative to the project root: the lanes themselves, this tool, and Flisk's saved plan and Tiltfile. */
const SKIP_FROM_ROOT = new Set([".lanes", ".arena", "tools", [".flisk", ".flisk-out"].join(sep)]);

function skipped(sourceDir: string, path: string): boolean {
  return SKIP_ANYWHERE.has(basename(path)) || SKIP_FROM_ROOT.has(relative(sourceDir, path));
}

/**
 * Copies a Flisk project for a lane. Generated output is left behind so the lane's first `flisk up` regenerates it
 * with the lane's own project name. Entries are copied one by one because the target (.lanes/<name>) sits inside
 * the source, which a single recursive copy refuses.
 */
export function copyProject(sourceDir: string, targetDir: string): void {
  mkdirSync(targetDir, { recursive: true });
  for (const entry of readdirSync(sourceDir)) {
    const from = join(sourceDir, entry);
    if (skipped(sourceDir, from)) continue;
    cpSync(from, join(targetDir, entry), {
      recursive: true,
      filter: (path) => !skipped(sourceDir, path),
    });
  }
}
