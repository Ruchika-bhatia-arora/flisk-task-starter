import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync } from "node:fs";
import { dirname, join, normalize, relative, sep } from "node:path";

/** The app's own code. Flisk config (services/, .flisk/), .env and compose files are never an agent's change. */
export const APP_DIRS = ["vote", "result", "worker", "seed-data", "healthchecks"];
const SKIP = new Set(["node_modules", ".autogenerated", "bin", "obj", ".arena-tools", "__pycache__"]);

export interface FileChange {
  path: string;
  change: "modified" | "added" | "deleted";
  added: number;
  removed: number;
}

export interface LaneDiff {
  files: FileChange[];
  patch: string;
  added: number;
  removed: number;
}

/** Every file under the app folders, as paths relative to the project root with forward slashes. */
function appFiles(root: string): Set<string> {
  const found = new Set<string>();
  const walk = (dir: string) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (SKIP.has(entry.name)) continue;
      const path = join(dir, entry.name);
      if (entry.isDirectory()) walk(path);
      else if (entry.isFile()) found.add(relative(root, path).split(sep).join("/"));
    }
  };
  for (const dir of APP_DIRS) if (existsSync(join(root, dir))) walk(join(root, dir));
  return found;
}

async function unifiedDiff(path: string, from: string | null, to: string | null): Promise<string> {
  const proc = Bun.spawn(
    ["diff", "-u", "--label", from ? `a/${path}` : "/dev/null", "--label", to ? `b/${path}` : "/dev/null", from ?? "/dev/null", to ?? "/dev/null"],
    { stdout: "pipe", stderr: "pipe" },
  );
  const text = await new Response(proc.stdout).text();
  await proc.exited;
  return text;
}

function countLines(patch: string): { added: number; removed: number } {
  let added = 0;
  let removed = 0;
  for (const line of patch.split("\n")) {
    if (line.startsWith("+++") || line.startsWith("---")) continue;
    if (line.startsWith("+")) added++;
    else if (line.startsWith("-")) removed++;
  }
  return { added, removed };
}

/** What changed in a lane's app code compared with the base project. */
export async function diffLane(baseDir: string, laneDir: string): Promise<LaneDiff> {
  const baseFiles = appFiles(baseDir);
  const laneFiles = appFiles(laneDir);
  const paths = [...new Set([...baseFiles, ...laneFiles])].sort();
  const files: FileChange[] = [];
  const patches: string[] = [];
  for (const path of paths) {
    const inBase = baseFiles.has(path);
    const inLane = laneFiles.has(path);
    if (inBase && inLane) {
      const a = join(baseDir, path);
      const b = join(laneDir, path);
      if (statSync(a).size === statSync(b).size && readFileSync(a).equals(readFileSync(b))) continue;
    }
    const patch = await unifiedDiff(path, inBase ? join(baseDir, path) : null, inLane ? join(laneDir, path) : null);
    const change: FileChange["change"] = !inBase ? "added" : !inLane ? "deleted" : "modified";
    files.push({ path, change, ...countLines(patch) });
    patches.push(patch);
  }
  return {
    files,
    patch: patches.join(""),
    added: files.reduce((sum, file) => sum + file.added, 0),
    removed: files.reduce((sum, file) => sum + file.removed, 0),
  };
}

/** A diff path is only trusted when it stays inside one of the app folders. */
function assertAppPath(path: string): void {
  const clean = normalize(path).split(sep).join("/");
  const top = clean.split("/")[0];
  if (clean.startsWith("..") || clean.startsWith("/") || !APP_DIRS.includes(top) || clean.split("/").some((part) => SKIP.has(part))) {
    throw new Error(`Refusing to apply ${JSON.stringify(path)}: it is outside the app folders (${APP_DIRS.join(", ")})`);
  }
}

/**
 * Copies a lane's changed app files into the base project and removes the files it deleted. Every base file that
 * is overwritten or removed is first copied to `backupDir` under the same path. Returns the paths it changed.
 */
export function applyToBase(baseDir: string, laneDir: string, diff: LaneDiff, backupDir: string): string[] {
  for (const file of diff.files) assertAppPath(file.path);
  const written: string[] = [];
  for (const file of diff.files) {
    const target = join(baseDir, file.path);
    if (existsSync(target)) {
      mkdirSync(dirname(join(backupDir, file.path)), { recursive: true });
      copyFileSync(target, join(backupDir, file.path));
    }
    if (file.change === "deleted") {
      rmSync(target, { force: true });
    } else {
      mkdirSync(dirname(target), { recursive: true });
      copyFileSync(join(laneDir, file.path), target);
    }
    written.push(file.path);
  }
  return written;
}
